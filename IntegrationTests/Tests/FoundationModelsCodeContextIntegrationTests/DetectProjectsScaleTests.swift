import Foundation
import FoundationModelsExtras
import Testing

@testable import FoundationModelsCodeContext

extension ScaleBenchmarks {
    /// The benchmark of `CodeContext.detectProjects()` on a tree of the size of a Django clone,
    /// during the first index pass.
    ///
    /// The tree is synthetic, in the shape of a Django clone: 9500 Python files in many nested
    /// directories, the `.gitignore` of Django, the root markers `pyproject.toml` and `package.json`,
    /// JavaScript files below the root, and ignored folders (`node_modules/`, `docs/_build/`) that
    /// the walk must skip. A real `CodeContext` starts on the tree, and the test calls
    /// `detectProjects()` while the first index pass runs. The embedder of the context waits
    /// `ModelLatencyEmbedder.callLatency` in each call, like a real embedding model, thus the first
    /// pass is long and the call runs during the pass.
    ///
    /// The test records the wall time as a test attachment, and fails when the time is more than the
    /// settle period of the runCode tool of the agent (6 seconds). Before the fix, one call took 5 to
    /// 10 seconds on a Django clone in a debug build (the gitignore check made two standardized URLs
    /// for each pattern and each entry), and 13 to 33 seconds on the SWE-bench host.
    @Suite(.serialized)
    struct DetectProjectsScaleTests {
        /// The number of Python files in the synthetic tree. The walk of a Django clone sees 10296
        /// non-ignored entries (files and directories), thus with the other files and the
        /// directories this count makes a walk of the same size.
        private static let pythonFileCount = 9500

        /// The number of top-level packages. Each package holds sub-packages.
        private static let packageCount = 40

        /// The number of sub-packages in each package.
        private static let subPackageCount = 15

        /// The number of JavaScript files below the root.
        private static let javaScriptFileCount = 100

        /// The number of files in each ignored folder. The walk must skip them all.
        private static let ignoredFileCount = 500

        /// The dimension of the fake embedding vectors.
        private static let embeddingDimension = 8

        /// The time of one embed call of the embedder of the context. The first pass makes some tens
        /// of embed calls, thus with this latency it runs for more than a minute.
        private static let embedCallLatency: Duration = .seconds(2)

        /// The most wall time that one `detectProjects()` call can use: the settle period of the
        /// runCode tool of FoundationModelsACPAgent.
        private static let wallTimeBudget: Duration = .seconds(6)

        /// The `.gitignore` of django/django, with no change. The walk checks each entry against
        /// these patterns.
        private static let djangoGitignore = """
            # If you need to exclude files such as those generated by an IDE, use
            # $GIT_DIR/info/exclude or the core.excludesFile configuration variable as
            # described in https://git-scm.com/docs/gitignore

            *.egg-info
            *.pot
            *.py[co]
            .tox/
            __pycache__
            MANIFEST
            dist/
            docs/_build/
            docs/locale/
            node_modules/
            tests/coverage_html/
            tests/.coverage*
            build/
            tests/report/
            tests/screenshots/

            """

        @Test
        func detectProjectsOnADjangoSizeTreeAnswersInTheSettlePeriodDuringTheFirstIndexPass() async throws {
            try await withTemporaryWorkspace { root in
                try Self.writeTree(root: root)
                let context = try await CodeContext<ProcessLanguageServerConnection>(
                    rootDirectory: root,
                    embedder: ModelLatencyEmbedder(
                        wrapped: FakeEmbedder(vectorLength: Self.embeddingDimension),
                        callLatency: Self.embedCallLatency
                    ),
                    autoInstall: LspAutoInstall(isEnabled: false),
                    eventSource: nil
                )
                let (projects, wallTime, isPassRunning) = try await withAsyncCleanup {
                    try await context.start()
                    let firstPass = FirstPassProgress()
                    let passWatch = Task {
                        await context.waitForFirstIndexPass()
                        await firstPass.markComplete()
                    }
                    let clock = ContinuousClock()
                    let start = clock.now
                    let projects = try await context.detectProjects()
                    let wallTime = start.duration(to: clock.now)
                    let isPassRunning = await !firstPass.isComplete
                    passWatch.cancel()
                    return (projects, wallTime, isPassRunning)
                } cleanup: {
                    await context.stop()
                }
                Attachment.record("python files \(Self.pythonFileCount), wall time \(wallTime)\n", named: "detect-projects-during-first-pass.txt")

                #expect(isPassRunning, "the first index pass was complete before the call answered (wall time \(wallTime))")
                #expect(Set(projects.map(\.language)).isSuperset(of: ["python", "javascript"]))
                #expect(wallTime < Self.wallTimeBudget, "wall time \(wallTime)")
            }
        }

        // MARK: - The synthetic tree

        /// Writes the synthetic tree under `root`.
        /// - Parameter root: The workspace root.
        /// - Throws: The errors of the file writes.
        private static func writeTree(root: URL) throws {
            try write(djangoGitignore, to: ".gitignore", in: root)
            try write("[project]\nname = \"django\"\n", to: "pyproject.toml", in: root)
            try write("{\"name\": \"django\"}\n", to: "package.json", in: root)
            for fileIndex in 0..<pythonFileCount {
                try write("def function_\(fileIndex)():\n    return \(fileIndex)\n", to: pythonFilePath(fileIndex: fileIndex), in: root)
            }
            for fileIndex in 0..<javaScriptFileCount {
                try write("export const value = \(fileIndex);\n", to: "js_tests/admin/test\(fileIndex).js", in: root)
            }
            for fileIndex in 0..<ignoredFileCount {
                try write("module.exports = \(fileIndex);\n", to: "node_modules/package\(fileIndex)/index.js", in: root)
                try write("<html></html>\n", to: "docs/_build/page\(fileIndex).html", in: root)
            }
        }

        /// The path of one Python file of the synthetic tree, relative to the root.
        /// - Parameter fileIndex: The index of the file.
        /// - Returns: The relative path, two directory levels below the root package.
        private static func pythonFilePath(fileIndex: Int) -> String {
            let package = fileIndex % packageCount
            let subPackage = (fileIndex / packageCount) % subPackageCount
            return "django/package\(package)/sub\(subPackage)/module\(fileIndex).py"
        }
    }
}

/// Whether the first index pass of a context is complete.
private actor FirstPassProgress {
    /// `true` after the first index pass is complete.
    private(set) var isComplete = false

    /// Records that the first index pass is complete.
    func markComplete() {
        isComplete = true
    }
}

/// A `PooledEmbedding` that waits a fixed time in each call and then gives the vectors of another
/// embedder, like a real embedding model that needs time for each call.
private struct ModelLatencyEmbedder: PooledEmbedding {
    /// The embedder that makes the vectors.
    let wrapped: FakeEmbedder

    /// The time that each call waits before it gives the vectors.
    let callLatency: Duration

    /// Waits `callLatency`, then gives the vectors of `wrapped`.
    ///
    /// - Parameter texts: The texts to embed.
    /// - Returns: One vector for each text.
    /// - Throws: `CancellationError` when the task of the caller is cancelled during the wait.
    func embed(texts: [String]) async throws -> [[Float]] {
        try await Task.sleep(for: callLatency)
        return try await wrapped.embed(texts: texts)
    }
}
